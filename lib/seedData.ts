// Helper to compute line item financials
export function computeItemFinancials(
  costPrice: number,
  sellingPrice: number,
  quantity: number
) {
  const totalCost = Number((costPrice * quantity).toFixed(2));
  const totalSelling = Number((sellingPrice * quantity).toFixed(2));
  const profit = Number((totalSelling - totalCost).toFixed(2));
  const marginPercent = totalSelling > 0 ? Number(((profit / totalSelling) * 100).toFixed(1)) : 0;
  return { totalCost, totalSelling, profit, marginPercent };
}

// Helper to compute order financials
export function computeOrderFinancials(
  items: Array<{ costPrice: number; sellingPrice: number; quantity: number }>,
  taxRate: number = 8,
  shippingCost: number = 25,
  discount: number = 0
) {
  const subtotalCost = items.reduce((sum, item) => sum + item.costPrice * item.quantity, 0);
  const subtotalSelling = items.reduce((sum, item) => sum + item.sellingPrice * item.quantity, 0);
  const taxAmount = Number(((subtotalSelling * taxRate) / 100).toFixed(2));
  const grandTotal = Number((subtotalSelling + taxAmount + shippingCost - discount).toFixed(2));
  const netProfit = Number((grandTotal - subtotalCost - shippingCost * 0.4).toFixed(2)); // deducting actual carrier cost
  const marginPercent = grandTotal > 0 ? Number(((netProfit / grandTotal) * 100).toFixed(1)) : 0;

  return {
    subtotalCost: Number(subtotalCost.toFixed(2)),
    subtotalSelling: Number(subtotalSelling.toFixed(2)),
    taxAmount,
    grandTotal,
    totalCost: Number(subtotalCost.toFixed(2)),
    netProfit,
    marginPercent,
  };
}

